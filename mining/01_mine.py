"""Minera issues fechadas por PR mesclado no período configurado, nos
repositórios selecionados por 00_select_repos.py (data/repos.csv).

Filtros por PR:
  P1  autor do PR não é bot nem agente de IA conhecido
  P2  PR e commits sem marcas de geração por IA (ex.: "Generated with Claude Code")
  vínculo com issue ("fixes #N"), issue com texto, PR altera código e testes,
  até max_code_files arquivos de código.

Saídas: data/candidates.jsonl e data/mining_log.csv (todo PR avaliado e o motivo
de descarte, para relatar no artigo).
Requer a variável de ambiente GITHUB_TOKEN.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.github import API, get  # noqa: E402
from common.utils import DATA, append_jsonl, load_config, read_jsonl, split_patch, patch_files  # noqa: E402

FIX_RE = re.compile(r"(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)", re.I)

# P1: contas de bots e agentes de codificação conhecidos
AI_AUTHORS = re.compile(r"\[bot\]$|^(copilot|copilot-swe-agent|devin-ai-integration|"
                        r"claude|codex|openhands-agent|sweep-ai|cursoragent|"
                        r"google-labs-jules|codegen-sh|ellipsis-dev)$", re.I)
# P2: marcas deixadas por ferramentas de geração de código
AI_MARKERS = re.compile(
    r"generated with \[?claude|co-authored-by:\s*(claude|copilot|cursor|codex|"
    r"openhands|devin-ai|devin ai|gemini|aider)\b|claude code|\bcodex\b|cursor agent|"
    r"copilot (coding )?agent|openhands|aider:|🤖 generated|"
    r"generated by (chatgpt|gpt-|an? (ai|llm))|written (by|with) (ai|chatgpt|claude)", re.I)


def log(row: list) -> None:
    path = DATA / "mining_log.csv"
    new = not path.exists()
    with path.open("a", newline="") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["repo", "pr_number", "status", "reason"])
        w.writerow(row)


def ai_signal(pr: dict) -> str | None:
    login = pr["user"]["login"]
    if pr["user"].get("type") == "Bot" or AI_AUTHORS.search(login):
        return f"P1_autor_bot_ou_ia:{login}"
    commits = get(pr["commits_url"], per_page=100).json()
    texts = [pr.get("body") or "", pr["title"]] + [
        c["commit"]["message"] for c in commits if isinstance(c, dict)]
    authors = [((c.get("author") or {}).get("login") or "") for c in commits if isinstance(c, dict)]
    if any(AI_AUTHORS.search(a) for a in authors if a):
        return "P1_commit_de_bot_ou_ia"
    m = next((AI_MARKERS.search(t) for t in texts if AI_MARKERS.search(t)), None)
    if m:
        return f"P2_marca_ia:{m.group(0)[:40]}"
    return None


def selected_repos() -> list[str]:
    path = DATA / "repos.csv"
    if not path.exists():
        sys.exit("data/repos.csv não encontrado: rode mining/00_select_repos.py antes.")
    return [r["repo"] for r in csv.DictReader(path.open()) if r["status"] == "selected"]


def merged_prs(repo: str, since: str, until: str):
    q = f"repo:{repo} is:pr is:merged merged:{since}..{until}"
    page = 1
    while True:
        r = get(f"{API}/search/issues", q=q, per_page=100, page=page)
        r.raise_for_status()
        items = r.json()["items"]
        yield from items
        if len(items) < 100 or page >= 10:
            return
        page += 1


def main() -> None:
    cfg = load_config()["mining"]
    out = DATA / "candidates.jsonl"
    existing = read_jsonl(out)
    seen = {c["instance_id"] for c in existing}
    logged = set()
    if (DATA / "mining_log.csv").exists():
        logged = {(r["repo"], r["pr_number"]) for r in csv.DictReader((DATA / "mining_log.csv").open())}
    for repo in selected_repos():
        count = sum(1 for c in existing if c["repo"] == repo)  # permite retomar
        for item in merged_prs(repo, cfg["since"], cfg["until"]):
            if count >= cfg["max_candidates_per_repo"]:
                break
            if (repo, str(item["number"])) in logged:
                continue
            pr = get(item["pull_request"]["url"]).json()

            def skip(reason: str) -> None:
                log([repo, pr["number"], "excluded", reason])

            refs = FIX_RE.findall(pr.get("body") or "") + FIX_RE.findall(pr["title"])
            if not refs:
                skip("sem_vinculo_issue")
                continue
            issue_no = int(refs[0])
            iid = f"{repo.replace('/', '__')}-{issue_no}"
            if iid in seen:
                skip("issue_duplicada")
                continue
            issue = get(f"{API}/repos/{repo}/issues/{issue_no}").json()
            if "pull_request" in issue or "title" not in issue or not (issue.get("body") or "").strip():
                skip("issue_invalida_ou_sem_texto")
                continue
            diff = get(pr["url"], headers={"Accept": "application/vnd.github.v3.diff"}).text
            code_patch, test_patch = split_patch(diff)
            code_files = [f for f in patch_files(code_patch) if f.endswith(".py")]
            if not code_files:
                skip("sem_codigo_python")
                continue
            if not test_patch:
                skip("sem_testes")
                continue
            if len(patch_files(code_patch)) > cfg["max_code_files"]:
                skip("patch_grande")
                continue
            ai = ai_signal(pr)
            if ai:
                skip(ai)
                continue
            append_jsonl(out, {
                "instance_id": iid,
                "repo": repo,
                "issue_number": issue_no,
                "issue_title": issue["title"],
                "issue_body": issue["body"],
                "pr_number": pr["number"],
                "pr_author": pr["user"]["login"],
                "base_commit": None,  # resolvido em 02_validate.py (pai do merge commit)
                "merge_commit": pr["merge_commit_sha"],
                "code_patch": code_patch,
                "test_patch": test_patch,
                "created_at": issue["created_at"],
            })
            log([repo, pr["number"], "candidate", iid])
            seen.add(iid)
            count += 1
            print(f"[+] {iid}")
        print(f"== {repo}: {count} candidatos")


if __name__ == "__main__":
    main()
